"""Deterministic synthetic data with a known data-generating mechanism.

Every generator separates the *true* event probability (``latent_p_true``, which a real
dataset never reveals) from the *model outputs* (``p_*`` columns), which are deliberate,
documented distortions of it. Outcomes are sampled once from Bernoulli(latent_p_true) with a
seeded generator; they are never edited after looking at metrics. All output is synthetic.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from scipy.special import expit, logit

SYNTHETIC_NOTE = ("SYNTHETIC DATA generated by calibcheck.synthetic with a known mechanism; "
                  "prevalences and results are properties of the generator, not empirical facts.")


@dataclass
class Scenario:
    name: str
    description: str
    frame: pd.DataFrame
    params: dict[str, Any]
    seed: int
    prob_columns: list[str]
    expected_interpretation: str
    dependence: str = "independent"
    group_columns: list[str] = field(default_factory=list)
    timestamp_column: str | None = None
    entity_column: str | None = None
    synthetic: bool = True

    def write(self, path: str | Path, *, include_latent: bool = False) -> Path:
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        df = self.frame if include_latent else self.frame.drop(columns=["latent_p_true"],
                                                               errors="ignore")
        df.to_csv(p, index=False)
        return p


def _ids(n: int, start: int = 1) -> list[str]:
    return [f"{i:06d}" for i in range(start, start + n)]


def _base(rng: np.random.Generator, n: int, beta0: float, beta1: float) -> tuple[np.ndarray, np.ndarray]:
    x = rng.standard_normal(n)
    p_true = expit(beta0 + beta1 * x)
    return x, p_true


def _sample(rng: np.random.Generator, p_true: np.ndarray) -> np.ndarray:
    return (rng.random(p_true.size) < p_true).astype(int)


def _frame(p_true: np.ndarray, y: np.ndarray, models: dict[str, np.ndarray], **extra: Any) -> pd.DataFrame:
    df = pd.DataFrame({"row_id": _ids(y.size), "y_true": y})
    for k, v in models.items():
        df[k] = np.round(v, 6)
    for k, v in extra.items():
        df[k] = v
    df["latent_p_true"] = np.round(p_true, 6)
    return df


def _split(rng: np.random.Generator, n: int, frac_cal: float = 0.5) -> np.ndarray:
    perm = rng.permutation(n)
    roles = np.empty(n, dtype=object)
    k = round(frac_cal * n)
    roles[perm[:k]] = "calibration"
    roles[perm[k:]] = "test"
    return roles


def distorted(p_true: np.ndarray, slope: float = 1.0, intercept: float = 0.0) -> np.ndarray:
    """Model output sigmoid(slope * logit(p_true) + intercept)."""
    return expit(slope * logit(np.clip(p_true, 1e-12, 1 - 1e-12)) + intercept)


def headline(n: int = 6000, seed: int = 7, cohort_fraction: float = 0.3,
             cohort_pred: float = 0.90, cohort_true: float = 0.65) -> Scenario:
    """A cohort receives P=0.90 while its outcomes are Bernoulli(0.65)."""
    rng = np.random.default_rng(seed)
    cohort = rng.random(n) < cohort_fraction
    _, p_rest = _base(rng, n, -1.0, 1.2)
    p_true = np.where(cohort, cohort_true, p_rest)
    p_model = np.where(cohort, cohort_pred, p_rest)
    y = _sample(rng, p_true)
    roles = _split(rng, n)
    df = _frame(p_true, y, {"p_model": p_model}, segment=np.where(cohort, "flagged", "other"),
                split=roles)
    return Scenario(
        name="headline", seed=seed, prob_columns=["p_model"], group_columns=["segment"],
        description=(f"{cohort_fraction:.0%} of rows form a 'flagged' cohort that the model scores "
                     f"at {cohort_pred:.2f}, while their outcomes are sampled from "
                     f"Bernoulli({cohort_true:.2f}). Other rows are calibrated by construction."),
        frame=df, params={"n": n, "cohort_fraction": cohort_fraction, "cohort_pred": cohort_pred,
                          "cohort_true": cohort_true, "rest": "p = sigmoid(-1 + 1.2 x), x~N(0,1)"},
        expected_interpretation=(
            "The [0.9, 1.0] bin should show an observed rate near (not exactly) 0.65. Within the "
            "flagged cohort all predictions are identical, so it shows probability bias without "
            "any ranking ability. A recalibrator fitted on the calibration rows can learn a value "
            "near the calibration cohort rate; its effect must be judged on the test rows."))


def _simple(name: str, description: str, interp: str, slope: float = 1.0, intercept: float = 0.0,
            beta0: float = -0.5, beta1: float = 1.0, extra_models: dict[str, tuple[float, float]] | None = None
            ) -> Callable[..., Scenario]:
    def gen(n: int = 4000, seed: int = 11) -> Scenario:
        rng = np.random.default_rng(seed)
        _, p_true = _base(rng, n, beta0, beta1)
        y = _sample(rng, p_true)
        models = {"p_model": distorted(p_true, slope, intercept)}
        for k, (s, b) in (extra_models or {}).items():
            models[k] = distorted(p_true, s, b)
        df = _frame(p_true, y, models, split=_split(rng, n))
        return Scenario(name=name, description=description, frame=df, seed=seed,
                        prob_columns=list(models),
                        params={"n": n, "beta0": beta0, "beta1": beta1, "slope": slope,
                                "intercept": intercept, "extra_models": extra_models or {}},
                        expected_interpretation=interp)
    return gen


calibrated = _simple("calibrated", "Model output equals the true probability.",
                     "Bin gaps should be compatible with sampling noise; recalibration has little "
                     "room to help and may slightly hurt on held-out data.")
overconfident = _simple("overconfident", "logit slope 2.0: predictions too extreme.",
                        "Overprediction at high probabilities, underprediction at low ones.",
                        slope=2.0)

"""Reproducible performance measurements (descriptive analysis, bootstrap, rendering).

Measures wall-clock time (time.perf_counter, best of `--repeat`) and peak traced memory
(tracemalloc, which tracks NumPy allocations; it does not include interpreter baseline or
memory held by native libraries outside NumPy). Inputs are generated, seeded and synthetic.
Results are written to benchmarks/results.md. Targets are goals, not claims.

Usage: python benchmarks/bench.py [--sizes 10000 100000 1000000] [--repeat 3]
"""

from __future__ import annotations

import argparse
import platform
import sys
import tempfile
import time
import tracemalloc
from pathlib import Path

import numpy as np
import pandas as pd

from calibcheck.analysis import analyze_data
from calibcheck.config import resolve_config
from calibcheck.data import load_predictions
from calibcheck.provenance import dependency_versions
from calibcheck.report import render_report


def make_frame(n: int, seed: int = 0) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    p_true = 1 / (1 + np.exp(-rng.normal(-0.5, 1.2, n)))
    y = (rng.random(n) < p_true).astype(np.int8)
    p = 1 / (1 + np.exp(-(1.5 * np.log(p_true / (1 - p_true)))))
    return pd.DataFrame({"row_id": np.arange(n).astype(str), "y": y, "p": p,
                         "q": np.clip(p_true + rng.normal(0, 0.02, n), 0, 1)})


def measure(fn, repeat: int) -> tuple[float, float]:
    """Best wall-clock time over `repeat` untraced runs, then one separate traced run for
    peak memory (tracemalloc slows Python-level allocation, so it never overlaps timing)."""
    best = float("inf")
    for _ in range(repeat):
        t = time.perf_counter()
        fn()
        best = min(best, time.perf_counter() - t)
    tracemalloc.start()
    fn()
    peak = tracemalloc.get_traced_memory()[1] / 1e6
    tracemalloc.stop()
    return best, peak


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sizes", type=int, nargs="+", default=[10_000, 100_000, 1_000_000])
    ap.add_argument("--repeat", type=int, default=3)
    ap.add_argument("--resamples", type=int, default=2000)
    a = ap.parse_args()
    rows = []
    for n in a.sizes:
        df = make_frame(n)
        base = {"columns": {"label": "y", "probs": ["p", "q"], "id": "row_id"}}
        cfg_desc = resolve_config(base, {"uncertainty": {"bootstrap": False}})
        cfg_boot = resolve_config(base, {"uncertainty": {"bootstrap": True,
                                                         "n_resamples": a.resamples}})
        t_load, m_load = measure(lambda: load_predictions(df, cfg_desc), a.repeat)
        data = load_predictions(df, cfg_desc)
        t_desc, m_desc = measure(lambda: analyze_data(data, cfg_desc), a.repeat)
        rep = 1 if n >= 1_000_000 else a.repeat
        t_boot, m_boot = measure(lambda: analyze_data(data, cfg_boot), rep)
        res = analyze_data(data, cfg_desc)
        with tempfile.TemporaryDirectory() as tmp:
            counter = iter(range(100))
            t_rend, m_rend = measure(
                lambda: render_report(res, Path(tmp) / f"r{next(counter)}"), a.repeat)
        rows.append({"rows": n, "validate_load_s": t_load, "validate_peak_MB": m_load,
                     "descriptive_s": t_desc, "descriptive_peak_MB": m_desc,
                     f"bootstrap_{a.resamples}_s": t_boot, "bootstrap_peak_MB": m_boot,
                     "render_s": t_rend, "render_peak_MB": m_rend})
        print(rows[-1], flush=True)
    out = pd.DataFrame(rows)
    lines = [
        "# Benchmark results (generated by benchmarks/bench.py)",
        "",
        f"- Machine: {platform.machine()} / {platform.system()} {platform.release()}; "
        f"Python {sys.version.split()[0]}",
        f"- Libraries: {', '.join(f'{k} {v}' for k, v in dependency_versions().items())}",
        f"- Configuration: 2 probability columns on the same rows, uniform 10 bins, binning "
        f"sensitivity on (5/10/20 × uniform/quantile), paired comparison; bootstrap "
        f"{a.resamples} percentile replicates of Brier, log loss, mean error and paired "
        "differences; default batch budget 4,000,000 index elements.",
        f"- Timing: best of {a.repeat} untraced runs (bootstrap at 1,000,000 rows: 1 run), "
        "time.perf_counter. Memory: one separate run under tracemalloc (peak of traced "
        "NumPy/Python allocations; excludes interpreter baseline and non-NumPy native memory).",
        "- Input: synthetic, generated in memory by `make_frame(n, seed=0)`; validation starts "
        "from a pandas DataFrame, so CSV parsing time is not included.",
        "",
        "| " + " | ".join(out.columns) + " |",
        "|" + "---|" * len(out.columns),
    ]
    for _, r in out.iterrows():
        lines.append("| " + " | ".join(f"{int(v):,}" if k == "rows" else f"{v:.3f}"
                                       for k, v in r.items()) + " |")
    Path(__file__).with_name("results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
